#!/usr/bin/env bash
# Regenerate docs/evidence/phase1-run.md from a real, unedited run.
# Nothing in the evidence file is hand-written: every line below is captured
# from this execution. Re-run to refresh it.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/docs/evidence/phase1-run.md"
source "$ROOT/scripts/db-env.sh"
mkdir -p "$ROOT/docs/evidence"

{
  echo "# Phase 1 — Execution Evidence"
  echo
  echo "Generated by \`scripts/run-phase1-evidence.sh\`. Every result below is"
  echo "captured from that run; nothing is transcribed by hand."
  echo
  echo "- PostgreSQL: \`$(psql -tAc 'show server_version')\`"
  echo "- Generated: $(date -u '+%Y-%m-%d %H:%M UTC')"
  echo

  echo '## 1. Schema and seed rebuild'
  echo
  echo '```'
  "$ROOT/scripts/reset-db.sh" 2>&1 | grep -vE 'NOTICE.*does not exist'
  echo '```'

  echo
  echo '## 2. Table row counts'
  echo
  echo '```'
  psql -c "
    SELECT t.relname                          AS table,
           t.n_live_tup                      AS rows,
           pg_size_pretty(pg_total_relation_size(t.relid)) AS size
    FROM   pg_stat_user_tables t
    ORDER  BY t.relname;"
  echo '```'

  for f in "$ROOT"/database/queries/*.sql; do
    echo
    echo "## $(basename "$f")"
    echo
    echo '```'
    psql -q -v ON_ERROR_STOP=1 -f "$f" 2>&1
    echo '```'
  done

  echo
  echo '## test_constraints.py'
  echo
  echo '```'
  "$ROOT/.venv/bin/pytest" "$ROOT/tests/database" -v 2>&1 | tail -60
  echo '```'

  echo
  echo '## Seed left unmodified by the test run'
  echo
  echo '```'
  psql -c "SELECT relname AS table, n_live_tup AS rows
           FROM pg_stat_user_tables ORDER BY relname;"
  echo '```'
} > "$OUT"

echo "==> Wrote ${OUT#$ROOT/}"